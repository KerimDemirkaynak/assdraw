#!/usr/bin/env python3
"""Embed the pinned Font Awesome SVG subset; retain source attribution."""
import re
import sys
from pathlib import Path

ICONS = {
    "Clear": "solid/broom", "Preview": "solid/eye", "Color": "solid/palette",
    "Drag": "solid/arrow-pointer", "Move": "solid/location-dot", "Line": "solid/slash",
    "Bezier": "solid/bezier-curve", "DeletePoint": "solid/eraser",
    "ScaleRotate": "solid/arrows-rotate", "Bilinear": "regular/object-group",
    "PanDrawing": "solid/draw-polygon", "PanBackground": "solid/image",
    "Save": "solid/plus", "SelectAll": "regular/square-check",
    "SelectNone": "regular/square", "DeleteShapes": "solid/trash-can", "Copy": "regular/copy",
}


def embed(source, destination):
    parts = ["// Generated by tools/embed_icons.py. Font Awesome Free 7.2.0: CC BY 4.0.\n",
             "#pragma once\nnamespace AssdrawIconData {\n"]
    for name, path in ICONS.items():
        svg = (source / "svgs" / (path + ".svg")).read_text(encoding="utf-8").strip()
        box = re.search(r'viewBox="([^"]+)"', svg)
        x, y, width, height = map(float, box[1].split())
        side = max(width, height) * 1.12
        # Give all glyphs a consistent square footprint and transparent padding.
        view = f"{x+(width-side)/2:g} {y+(height-side)/2:g} {side:g} {side:g}"
        svg = re.sub(r'<svg\b[^>]*>',
                     f'<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="{view}">', svg, count=1)
        if 'fill="currentColor"' not in svg:
            raise ValueError(f"Missing theme colour in {path}")
        parts.append(f'inline constexpr char {name}[] = R"svg({svg})svg";\n')
    parts.append("}\n")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("".join(parts), encoding="utf-8")


if __name__ == "__main__":
    embed(Path(sys.argv[1]), Path(sys.argv[2]))
