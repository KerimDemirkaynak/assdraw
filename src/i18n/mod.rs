//! Localization and internationalization for ASSDraw-rs.
//! Supports 7 languages: English (en), Turkish (tr), French (fr), German (de), Spanish (es), Traditional Chinese (zh_TW), Vietnamese (vi).

use serde::{Deserialize, Serialize};

mod ui_strings;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
pub enum Language {
    #[default]
    En,
    Tr,
    Fr,
    De,
    Es,
    ZhTw,
    Vi,
}

impl Language {
    pub const ALL: [Language; 7] = [
        Language::En,
        Language::Tr,
        Language::Fr,
        Language::De,
        Language::Es,
        Language::ZhTw,
        Language::Vi,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::Tr => "tr",
            Language::Fr => "fr",
            Language::De => "de",
            Language::Es => "es",
            Language::ZhTw => "zh_TW",
            Language::Vi => "vi",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Language::En => "English",
            Language::Tr => "Türkçe",
            Language::Fr => "Français",
            Language::De => "Deutsch",
            Language::Es => "Español",
            Language::ZhTw => "繁體中文",
            Language::Vi => "Tiếng Việt",
        }
    }

    /// Language of the operating system (from the usual locale variables), English otherwise.
    pub fn detect() -> Self {
        for var in ["LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"] {
            if let Ok(v) = std::env::var(var) {
                let v = v.to_lowercase();
                if v.is_empty() || v == "c" || v == "posix" {
                    continue;
                }
                if v.starts_with("zh") {
                    return Language::ZhTw;
                }
                let code: String = v.chars().take_while(|c| c.is_ascii_alphabetic()).collect();
                return Self::from_code(&code);
            }
        }
        Language::En
    }

    pub fn from_code(s: &str) -> Self {
        match s.to_lowercase().as_str() {
            "tr" => Language::Tr,
            "fr" => Language::Fr,
            "de" => Language::De,
            "es" => Language::Es,
            "zh" | "zh_tw" | "zh-tw" | "zh-hant" => Language::ZhTw,
            "vi" => Language::Vi,
            _ => Language::En,
        }
    }
}

pub fn t(lang: Language, key: &'static str) -> &'static str {
    if let Some(s) = ui_strings::lookup(lang, key) {
        return s;
    }
    match lang {
        Language::Tr => tr_tr(key),
        Language::En => tr_en(key),
        Language::Fr => tr_fr(key),
        Language::De => tr_de(key),
        Language::Es => tr_es(key),
        Language::ZhTw => tr_zh(key),
        Language::Vi => tr_vi(key),
    }
}

